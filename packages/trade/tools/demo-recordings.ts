// Writes src/market/recorded-data.ts, ?demo's market data, from the answers recorded read-only on 25 Oct 2026 (src/market/fixtures/):
// the four trending lists, one coin per chain (token + info), and CoinGecko's native prices; plus coins-extra.json (27 Oct
// 2026, read-only through the market relay): the info (holders, score, creator) of each chain's top six trending coins, with
// no price of their own, so a page's price is its list row's. Run: node packages/trade/tools/demo-recordings.ts
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../src/market/fixtures/", import.meta.url));
const fx = (name: string): unknown => JSON.parse(readFileSync(`${dir}${name}.json`, "utf8"));
const token = (name: string) => fx(name) as { data: { attributes: { address: string } } };
const keyed = (net: string, name: string, info: string) => [`${net}:${token(name).data.attributes.address.toLowerCase()}`, { token: fx(name), info: fx(info) }] as const;
const data = {
  // NEAR (TN1): its trending list and QTC's token and info, recorded read-only on 2 Nov 2026
  trending: { all: fx("trending-all"), solana: fx("trending-solana"), bsc: fx("trending-bsc"), robinhood: fx("trending-robinhood"), near: fx("trending-near") },
  // the extras first: a coin recorded whole on 25 Oct keeps its own token answer
  coins: { ...(fx("coins-extra") as Record<string, { info: unknown }>), ...Object.fromEntries([keyed("solana", "token-sol", "info-sol"), keyed("bsc", "token-bsc", "info-bsc"), keyed("robinhood", "token-hood", "info-hood"), keyed("near", "token-near", "info-near")]) },
  nativeUsd: fx("cg-simple-price"),
  // the Sim's New tab: Solana's new pools as GeckoTerminal answered on 25 Oct (the other networks' New are their recorded
  // pools, newest first: recorded.ts newPools)
  fresh: { solana: fx("new-pools-sol") },
};
// The data is a .json beside a two-line module (the landing's gate holds every code line under 800 characters; JSON
// is data, never run)
const json = fileURLToPath(new URL("../src/market/recorded-data.json", import.meta.url));
writeFileSync(json, JSON.stringify(data) + "\n");
const out = fileURLToPath(new URL("../src/market/recorded-data.ts", import.meta.url));
writeFileSync(out, `// Generated by tools/demo-recordings.ts from fixtures/ (GeckoTerminal and CoinGecko, recorded 25 and 27 Oct 2026; NEAR 2 Nov 2026). Don't edit by hand.
import type { Recordings } from "./recorded.ts";
import data from "./recorded-data.json" with { type: "json" };
export const RECORDED = data as unknown as Recordings;
`);
console.log(`wrote ${out}`);
