#!/usr/bin/env bash
# fetch.sh - copy the exact BitChat iOS source files this harness compiles,
# read straight out of git at one pinned commit (never from a working tree).
#
#   bash fetch.sh [path-to-bitchat-clone]
#
# Clone: $1, else $BITCHAT_SRC, else a blobless clone made in
# ~/.cache/zerofee/bitchat (from https://github.com/permissionlesstech/bitchat).
# BitChat iOS is released into the public domain (Unlicense). Only .swift and
# fixture .json files are read; nothing from the clone is executed (no
# Package.swift, no scripts). The Android repo (GPL) is never used.
#
# Copied files land in git-ignored folders:
#   Sources/BitLogger/       localPackages/BitLogger/Sources/*.swift
#   Sources/BitFoundation/   localPackages/BitFoundation/Sources/BitFoundation/*.swift
#   Sources/harness/BitChat/ the app files listed in APP_FILES, plus a
#                            generated Manifest.swift (commit, sha256 of every
#                            copied file as fetched, the frozen fixtures)
#
# One patch, and it touches no BitChat line: seam/NostrProtocolHarnessSeam.swift.in
# is APPENDED to the copy of NostrProtocol.swift. It is an extension of
# NostrProtocol that only forwards to the file's private helpers (encrypt,
# decrypt, deriveSharedSecret, derivePrivateEnvelopeKey, createSeal,
# createGiftWrap), which Swift lets an extension in the same file reach.
# The recorded sha256 is of the file before the append, so it matches
# `git show <commit>:bitchat/Nostr/NostrProtocol.swift | shasum -a 256`.
set -euo pipefail

COMMIT=04995f68e470a18d1fc99f86fa326c2a87bab4f2
REPO_URL=https://github.com/permissionlesstech/bitchat.git
HERE="$(cd "$(dirname "$0")" && pwd)"
SRC="${1:-${BITCHAT_SRC:-$HOME/.cache/zerofee/bitchat}}"

APP_FILES=(
  bitchat/Nostr/NostrProtocol.swift
  bitchat/Nostr/XChaCha20Poly1305Compat.swift
  bitchat/Nostr/Base64URLCoding.swift
  bitchat/Nostr/NostrIdentity.swift
  bitchat/Nostr/NostrEmbeddedBitChat.swift
  bitchat/Nostr/Bech32.swift
  bitchat/Protocols/Packets.swift
  bitchat/Protocols/BitchatProtocol.swift
  bitchat/Models/NoisePayload.swift
)
FIXTURES=(
  bitchatTests/Nostr/Fixtures/LegacyPrivateEnvelope733098bb.json
  bitchatTests/Nostr/Fixtures/LegacyPrivateEnvelope733098bbRecipientKey.json
  bitchatTests/Nostr/Fixtures/AndroidLegacyPrivateEnvelopeB7f0b33d.json
  bitchatTests/Nostr/Fixtures/AndroidLegacyPrivateEnvelopeB7f0b33dMetadata.json
)

if [ ! -d "$SRC/.git" ] && [ ! -f "$SRC/HEAD" ]; then
  echo "fetch.sh: no clone at $SRC, cloning $REPO_URL (blobless)" >&2
  mkdir -p "$(dirname "$SRC")"
  git clone --filter=blob:none --no-checkout --quiet "$REPO_URL" "$SRC"
fi
if ! git -C "$SRC" cat-file -e "$COMMIT^{commit}" 2>/dev/null; then
  git -C "$SRC" fetch --quiet --filter=blob:none origin "$COMMIT"
fi
# The pinned commit must be exactly this object, not a branch that moved.
[ "$(git -C "$SRC" rev-parse "$COMMIT^{commit}")" = "$COMMIT" ] || { echo "fetch.sh: commit mismatch" >&2; exit 1; }

LOGGER_DIR="$HERE/Sources/BitLogger"
FOUNDATION_DIR="$HERE/Sources/BitFoundation"
APP_DIR="$HERE/Sources/harness/BitChat"
rm -rf "$LOGGER_DIR" "$FOUNDATION_DIR" "$APP_DIR"
mkdir -p "$LOGGER_DIR" "$FOUNDATION_DIR" "$APP_DIR"

MANIFEST_ROWS=""
copy() { # copy <path-in-repo> <dest-file>
  git -C "$SRC" show "$COMMIT:$1" > "$2"
  local sum; sum="$(shasum -a 256 "$2" | cut -d' ' -f1)"
  MANIFEST_ROWS+="    (\"$1\", \"$sum\"),"$'\n'
}
list_swift() { # list_swift <dir-in-repo>
  git -C "$SRC" ls-tree --name-only "$COMMIT" "$1/" | grep '\.swift$'
}

for f in $(list_swift localPackages/BitLogger/Sources); do copy "$f" "$LOGGER_DIR/$(basename "$f")"; done
for f in $(list_swift localPackages/BitFoundation/Sources/BitFoundation); do copy "$f" "$FOUNDATION_DIR/$(basename "$f")"; done
for f in "${APP_FILES[@]}"; do copy "$f" "$APP_DIR/$(basename "$f")"; done

# The seam (see header). Appended after the sha256 was taken.
cat "$HERE/seam/NostrProtocolHarnessSeam.swift.in" >> "$APP_DIR/NostrProtocol.swift"

FIXTURE_ROWS=""
for f in "${FIXTURES[@]}"; do
  tmp="$(mktemp)"
  copy "$f" "$tmp"
  FIXTURE_ROWS+="    \"$(basename "$f" .json)\": \"$(base64 < "$tmp" | tr -d '\n')\","$'\n'
  rm -f "$tmp"
done

cat > "$APP_DIR/Manifest.swift" <<EOF
// Generated by fetch.sh. Not BitChat code; not committed.
let bitchatCommit = "$COMMIT"
let bitchatSourceFiles: [(path: String, sha256: String)] = [
$MANIFEST_ROWS]
/// Frozen fixtures from bitchatTests/Nostr/Fixtures, base64 of the file bytes.
let bitchatFixturesBase64: [String: String] = [
$FIXTURE_ROWS]
EOF

echo "fetch.sh: copied BitChat $COMMIT ($(printf '%s' "$MANIFEST_ROWS" | grep -c '(' || true) files) into $HERE/Sources" >&2
